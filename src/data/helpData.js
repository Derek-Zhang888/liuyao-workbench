/** 爻位称呼：lines 为 guaTable 爻画串（1=阳 2=阴），i 为 0-5 爻索引（初→上）
 *  规则：初爻「初九/初六」、上爻「上九/上六」；中间爻「九二…九五/六二…六五」（数字在前） */
export function yaoName(lines, i) {
  const yang = lines[i] === '1';
  if (i === 0) return '初' + (yang ? '九' : '六');
  if (i === 5) return '上' + (yang ? '九' : '六');
  return (yang ? '九' : '六') + ['二', '三', '四', '五'][i - 1];
}

